"""Rebuild the website's data files from the database.

Run from the repository root after editing anything in data/:
    python tools/build.py

It writes two files the website reads:
    data.js  <- data/db.json      (all content, English master)
    i18n.js  <- data/db_hi.json   (Hindi for every line, plus button and label text)
and then checks that every picture the content points to exists,
and that each Hindi line keeps the same numbers as its English line.
"""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
db = json.loads((ROOT / 'data/db.json').read_text(encoding='utf-8'))
hi = json.loads((ROOT / 'data/db_hi.json').read_text(encoding='utf-8'))

# 1. data.js: content only (internal bookkeeping keys are left out of the site)
site = {k: v for k, v in db.items() if k not in ('images', 'mergeLog03')}
(ROOT / 'data.js').write_text(
    f"// SAMVIDHAN — CONTENT DATABASE v{db['meta']['version']} (generated by tools/build.py from data/db.json; do not edit by hand)\n"
    f"const DB = {json.dumps(site, ensure_ascii=False)};\n", encoding='utf-8')

# 2. i18n.js: Hindi map + the language logic
H = {**hi['strings'], **hi['ui']}
core = (ROOT / 'tools/i18n_core.js').read_text(encoding='utf-8')
(ROOT / 'i18n.js').write_text('const HI = ' + json.dumps(H, ensure_ascii=False, separators=(',', ':')) + ';\n' + core, encoding='utf-8')

# 3. checks
problems = 0
paths = set(re.findall(r'"((?:art|face|pic|scene|scene-s)/[\w.-]+\.webp)"', json.dumps(site)))
for f in ('app.js', 'story.js', 'levels.js', 'animals.js'):
    paths |= set(re.findall(r"((?:art|face|pic|scene|scene-s)/[\w.-]+\.webp)", (ROOT / f).read_text(encoding='utf-8')))
for p in sorted(paths):
    if not (ROOT / p).exists():
        print('MISSING PICTURE', p); problems += 1
for en, h in hi['strings'].items():
    for n in re.findall(r'\d+(?:[.,]\d+)*', en):
        if n not in h:
            print('NUMBER NOT IN HINDI', n, '|', en[:70]); problems += 1
print(f"data.js and i18n.js rebuilt. {len(paths)} pictures referenced, {len(H)} Hindi lines. Problems: {problems}")
sys.exit(1 if problems else 0)
